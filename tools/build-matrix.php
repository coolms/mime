<?php

declare(strict_types=1);

/**
 * Builds CONFORMANCE.md by joining what the tests CLAIM with what the run PROVED.
 *
 * This is the half of the conformance gate that cannot be answered from inside a test
 * run: whether the test claiming a row actually passed. A hand-written matrix is a
 * statement of intent; this one is a report of a measurement, and it refuses to write
 * a file in which a row declared implemented has no passing evidence behind it.
 *
 * Usage:
 *   vendor/bin/phpunit --testsuite mime   --log-junit build/junit-mime.xml
 *   vendor/bin/phpunit --testsuite oracle --log-junit build/junit-oracle.xml
 *   php tools/build-matrix.php build/junit-mime.xml build/junit-oracle.xml
 *
 * The oracle log is optional: without it the rows verified only against the oracle
 * simply show fewer targets, which is the honest report for a run that did not have
 * the dev dependency installed.
 *
 * **A row is verified when AT LEAST ONE claiming test passed**, not when all of them
 * did -- a row backed by a unit case and an oracle comparison stays verified if the
 * unit case breaks, because the oracle comparison still measured it. The suite itself
 * goes red either way, so nothing is hidden; what this file answers is the narrower
 * question of whether the row has evidence. That rule has a consequence worth knowing
 * before trying to prove this gate works: breaking a test for a row with two
 * claimants changes nothing here, and a mutation aimed at this tool has to pick a row
 * with exactly one.
 */

require __DIR__ . '/../vendor/autoload.php';

use CoolMS\Mime\Tests\Conformance\ClaimedRows;
use CoolMS\Mime\Tests\Conformance\ConformanceMatrix;

$logs = array_slice($argv, 1);
if ([] === $logs) {
    fwrite(STDERR, "usage: php tools/build-matrix.php <junit.xml> [<junit.xml> ...]\n");
    exit(2);
}

/**
 * Which test methods passed, as `ShortClassName::method`.
 *
 * A method with a data provider appears once per data set; it counts as passing only
 * if EVERY one of its cases passed. A row backed by a test that is green for four
 * inputs and red for the fifth has not been verified.
 *
 * @return array<string, bool>
 */
function outcomes(array $logs): array
{
    $outcomes = [];

    foreach ($logs as $log) {
        if (!is_file($log)) {
            fwrite(STDERR, "note: {$log} not present; rows verified only there will show fewer targets\n");

            continue;
        }

        $xml = simplexml_load_file($log);
        if (false === $xml) {
            fwrite(STDERR, "could not read {$log}\n");
            exit(2);
        }

        foreach ($xml->xpath('//testcase') ?: [] as $case) {
            $class = (string) $case['class'];
            $name = (string) $case['name'];

            // "method with data set #3" / "method with data set \"name\"".
            $method = preg_replace('/ with data set .*$/', '', $name) ?? $name;
            $short = str_contains($class, '\\') ? substr(strrchr($class, '\\'), 1) : $class;
            $key = $short . '::' . $method;

            $failed = 0 !== count($case->failure) || 0 !== count($case->error);
            $outcomes[$key] = ($outcomes[$key] ?? true) && !$failed;
        }
    }

    return $outcomes;
}

$claims = ClaimedRows::collect(__DIR__ . '/../tests');
$outcomes = outcomes($logs);

$rows = ConformanceMatrix::rows();
$unverified = [];
$lines = [];

$lines[] = '# Conformance';
$lines[] = '';
$lines[] = 'Generated by `tools/build-matrix.php` from the test run. Do not edit by hand:';
$lines[] = 'a row is green because a test claiming it passed, and the build refuses to write';
$lines[] = 'this file when a row declared implemented has no passing test behind it.';
$lines[] = '';
$lines[] = '`verified against` is what the passing tests actually ran: `unit` for hand-written';
$lines[] = 'cases, `corpus` for the shared corpus, `oracle` for a differential comparison with';
$lines[] = 'another parser. More than one is stronger than any of them alone.';
$lines[] = '';
$lines[] = '| row | RFC | status | verified against | note |';
$lines[] = '| --- | --- | --- | --- | --- |';

foreach ($rows as $slug => $row) {
    $targets = [];
    foreach ($claims[$slug] ?? [] as $claim) {
        if ($outcomes[$claim['test']] ?? false) {
            $targets[$claim['against']] = true;
        }
    }
    ksort($targets);
    $against = [] === $targets ? '--' : implode(', ', array_keys($targets));

    if (ConformanceMatrix::IMPLEMENTED === $row['status'] && [] === $targets) {
        $unverified[] = $slug;
    }

    $lines[] = sprintf(
        '| `%s` | %s | %s | %s | %s |',
        $slug,
        $row['rfc'],
        ConformanceMatrix::IMPLEMENTED === $row['status'] ? 'implemented' : '**not implemented**',
        $against,
        $row['note'],
    );
}

$implemented = count(ConformanceMatrix::implementedRows());
$lines[] = '';
$lines[] = sprintf(
    '%d rows: %d implemented, %d explicitly not implemented.',
    count($rows),
    $implemented,
    count($rows) - $implemented,
);
$lines[] = '';

if ([] !== $unverified) {
    fwrite(STDERR, "REFUSING to write the matrix. These rows are declared implemented and no\n");
    fwrite(STDERR, "test claiming them passed in this run:\n");
    foreach ($unverified as $slug) {
        fwrite(STDERR, "  - {$slug}\n");
    }
    fwrite(STDERR, "\nEither the test failed, or no test claims the row. A matrix written anyway\n");
    fwrite(STDERR, "would be the claim this whole arrangement exists to replace.\n");
    exit(1);
}

file_put_contents(__DIR__ . '/../CONFORMANCE.md', implode("\n", $lines));
printf("CONFORMANCE.md written: %d rows, %d implemented and all verified.\n", count($rows), $implemented);
